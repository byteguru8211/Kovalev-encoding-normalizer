def _fld_char(p, ftype):
    r = p.add_run()
    fc = OxmlElement("w:fldChar")
    fc.set(qn("w:fldCharType"), ftype)
    r._element.append(fc)
    return r


def toc_entry(level, text, page, first=False, last=False):
    p = doc.add_paragraph()
    p.paragraph_format.first_line_indent = Cm(0)
    p.paragraph_format.left_indent = Cm(0 if level == 1 else 0.75)
    p.paragraph_format.space_after = Pt(2)
    p.paragraph_format.line_spacing_rule = WD_LINE_SPACING.SINGLE
    p.paragraph_format.tab_stops.add_tab_stop(Cm(16), WD_TAB_ALIGNMENT.RIGHT, leader=2)  # dot leader
    if first:
        _fld_char(p, "begin")
        ri = p.add_run()
        it = OxmlElement("w:instrText")
        it.set(qn("xml:space"), "preserve")
        it.text = r' TOC \o "1-2" \h \z \u '
        ri._element.append(it)
        _fld_char(p, "separate")
    run(p, text, bold=(level == 1), size=12)
    rr = p.add_run("\t" + str(page))
    rr.font.name = FONT
    rr.font.size = Pt(12)
    if last:
        _fld_char(p, "end")


