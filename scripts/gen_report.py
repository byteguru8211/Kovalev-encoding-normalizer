def run(p, text, bold=False, italic=False, size=None, align=None, indent=True, caps=False):
    if align is not None:
        p.alignment = align
    if not indent:
        p.paragraph_format.first_line_indent = Cm(0)
    r = p.add_run(text)
    r.font.name = FONT
    r.font.size = Pt(size or BODY)
    r.bold = bold
    r.italic = italic
    r._element.rPr.rFonts.set(qn("w:eastAsia"), FONT)
    return r


